# 시장봇: 대표 지수/환율/금 고정 세트 + 오늘 뉴스에 언급된 종목을 yfinance로 스냅샷.
# 독립 launchd 잡이 아니라 evening-chain.sh 의 2단계로 순서대로 불린다
# (뉴스레터 다이제스트 이후, 결론봇 이전 — §evening-chain.sh 참고).

set -euo pipefail

VAULT_DIR="/Users/gyuhyeongkim/orca/projects/quant_auto"
CLAUDE_BIN="/Users/gyuhyeongkim/.local/bin/claude"
LOG_DIR="$VAULT_DIR/.automation/logs"
LOG_FILE="$LOG_DIR/$(date +%Y%m%d).log"

mkdir -p "$LOG_DIR"
cd "$VAULT_DIR"

# 네트워크 대기·재시도 — 깨어난 직후 Wi-Fi 가 안 올라온 상태에서 죽는 것을 막는다.
# 대기 기록도 일별 로그에 남긴다 (건너뛴 이유가 어딘가엔 있어야 한다).
source "$VAULT_DIR/.automation/lib/net.sh"
if ! wait_for_network >> "$LOG_FILE" 2>&1; then
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') 네트워크 없음 — 이번 실행 건너뜀 ===" >> "$LOG_FILE"
  exit 0
fi


# 체인이 자정을 넘겨도 단계들이 같은 날짜를 쓰도록 CHAIN_DATE 를 우선한다
TODAY_KST="${CHAIN_DATE:-$(TZ=Asia/Seoul date +%y%m%d)}"
TODAY_ISO_KST=$(TZ=Asia/Seoul date -j -f %y%m%d "$TODAY_KST" +%Y-%m-%d)

PROMPT="오늘 날짜(KST): ${TODAY_ISO_KST} (YYMMDD: ${TODAY_KST})

용도: **블룸버그 터미널 매매대회 전략 세팅.** 대회는 전 세계 주식을 사고, 평가는
벤치마크 대비 상대수익률이다. 그래서 절대 시세가 아니라 **벤치마크를 이기는 쪽이
어디인가**를 본다. 숫자는 전부 스크립트가 계산하니 옮겨 적기만 한다.

작업:
1. personal/09-newsletters/_digests/${TODAY_KST}-일일요약.md 가 있으면 읽고, 거기 언급된
   **상장 기업**의 야후 파이낸스 티커를 뽑는다 (예: 메타→META, 삼성전자→005930.KS,
   소프트뱅크→9984.T). 비상장(SpaceX, OpenAI 등)이나 확실하지 않은 것은 넣지 않는다.
   다이제스트가 없으면 종목 없이 진행한다.
2. 다음을 Bash로 실행한다. 티커는 공백으로 구분해 뒤에 붙인다 (없으면 인자 없이):
   .automation/.venv/bin/python .automation/market_metrics.py <티커들...>
   출력 절: [레짐] [지역] [섹터] [스타일] [종목] [스크리닝] [브레드스] [실적발표] [포지션 사이징]
   [전략모드] [모멘텀] [빌드업] [백테스트] [체결추적] [스트레치] [상관]
   - [지역]/[섹터]/[스타일]/[종목]/[스크리닝] 은 raw 1개월 초과수익이 아니라 **위험조정
     점수(scr = 변동성 대비 초과수익)** 로 줄 세운 것이다 — 1개월 컬럼은 참고용으로 같이
     나온다. scr 이 높은데 1개월이 낮아 보이면 \"적게 흔들리며 꾸준히 이겼다\"는 뜻이고,
     반대로 1개월은 높은데 scr 이 낮으면 \"변동성에 기댄 반짝 초과수익\"이라고 짚는다
   - 표의 RS 열은 상대강도 지속일이다. 승N일 = 벤치마크를 N일째 이기는 중.
     3개월 성적이 좋아도 RS 가 '패'로 돌아섰으면 추세가 꺾인 것이므로 그 사실을 적는다
   - [스크리닝] 은 섹터·스타일 ETF 보유종목에서 만든 유니버스를 벤치마크 대비로 줄 세운 것이다.
     대회는 종목을 사므로 여기가 실제 매수 후보다. 티커 뒤 ⚡RSI 숫자는 모멘텀 과열/과매도 신호다
   - [브레드스] 는 몇 %가 벤치를 이기는지다. 낮으면 좁은 장(종목선택이 크게 먹힘)
   - [전략모드] 는 [브레드스] 수치를 근거로 스크립트가 낸 행동 권고다(\"로테이션 위주\" /
     \"스크리닝 위주\" / \"5:5\") — 그대로 인용한다. 판단을 다시 하거나 다른 말로 바꾸지 않는다
   - [포지션 사이징] 은 더 이상 flat 20%가 아니라 **역변동성 가중**이다 — 변동성 낮은
     종목이 20%에 가깝게, 높은 종목은 그보다 적게 담긴다(그래서 비중이 종목마다 다르다).
     '정보비율(표본내)'·'연환산 초과수익(표본내)'은 **방금 그 종목을 고른 기준과 같은
     구간**에서 잰 값이라 구조적으로 부풀려져 있다(스크립트 ※표시 그대로 옮긴다) — 낮아도
     이상한 게 아니라 그게 정상이고, 아주 높게 나온 건 '고른 기준으로 다시 잰 값이라
     원래 좋게 나온다'고 짚는다. '최대낙폭(절대)'는 북 자체 수익률 기준이라 [백테스트]
     의 최대낙폭(누적초과수익 기준)과 계산 대상이 달라 **나란히 비교하지 않는다**
   - [모멘텀] 은 RSI 과열(≥70)·과매도(≤30) 목록이다. 방금 며칠 이겼어도 RSI 과열이면
     단기 되돌림 위험이 있다는 뜻이므로 종목 후보를 고를 때 참고한다
   - [빌드업] 은 최근 실행 기록과 비교한 지속성이다. 단위가 '일째'가 아니라 **'회째'**다
     (실행을 건너뛴 날은 로그에 구멍이 나므로 영업일수와 다르다) — 그대로 '회째'로 옮긴다.
     '몇 회째 유지'가 길수록 확신도가 높고, 방금 뒤집혔으면(1~2회째) 아직 검증 안 된
     신호라고 짚는다. '기록 1회째'면 아직 쌓인 이력이 없다는 뜻이니 그대로 옮긴다
   - [백테스트] 는 지역·섹터·스타일 로테이션 규칙(오늘 쓰는 것과 같은 방법론)이 과거
     몇 달 실제로 벤치마크를 이겼는지다 — [포지션 사이징]의 표본내 지표와 달리 다음
     구간 실현수익으로 평가하므로 편향이 없다. '아직 없음'이면 그대로 적는다.
     '🔴 캐시가 N일째 안 갱신됨'이면 **숫자를 인용하지 말고** 그 경고 문장을 그대로
     옮긴다 — 오래된 숫자를 최신인 것처럼 쓰면 안 된다. 신선하면 적중률·정보비율·
     최대낙폭(누적초과수익)을 그대로 옮긴다. 개별종목 스크리닝과는 별개 검증이라는
     점(※표시)도 같이 옮긴다
   - [체결추적] 은 브리핑을 보고 **실제로** 블룸버그 터미널에서 산 종목(사람이
     .automation/log_trade.py 로 남긴 것)이 지금 신호대로 가고 있는지다. 신호(스크립트
     추정)와 다른 항목이니 헷갈리지 않게 구분해서 적는다. '기록된 체결 없음'이면
     그대로 적는다(진짜 아무것도 안 산 게 아니라 아직 기록을 안 한 것일 수도 있다는
     뜻이므로 '매매 없음'으로 바꿔 쓰지 않는다). 종목 아래에 🔴/🟡 로 시작하는 줄이
     있으면 **청산 후보**다(트레일링손절/손절/익절) — 이건 스크립트가 계산한 후보
     통지이지 매도 지시가 아니므로 '지금 팔아야 한다'가 아니라 '점검이 필요하다'는
     톤으로 옮긴다. 없으면 그 줄 자체를 생략한다(지어내지 않는다)
   **이 숫자를 그대로 옮겨 적는다. 직접 계산하거나 추정하지 않는다.**
3. personal/10-market/data/${TODAY_KST}-시장데이터.md 를 작성한다.
   **파일이 오늘 날짜로 이미 있어도 Edit 으로 일부만 고치지 말고, Write 로 아래
   내용 전체를 새로 써서 통째로 덮어쓴다.** (allowedTools 에 Edit 이 없다 —
   부분 수정을 시도하면 헤드리스에서 승인해 줄 사람이 없어 그대로 멈춘다.
   실제로 2026-08-24 에 이렇게 멈춰서 새 절이 하루 종일 안 들어간 적이 있다.)
   형식:
   ---
   date: ${TODAY_ISO_KST}
   ---

   # ${TODAY_KST} 마켓

   ## 레짐
   (스크립트 [레짐] 절 그대로 + 한 줄 해석)

   ## 벤치마크 대비 초과수익
   ### 지역 / ### 섹터 / ### 스타일
   각각 표로: | 이름 | scr(위험조정) | 1개월 | 3개월 | z | 베타 | 추세 |
   숫자는 스크립트 출력 그대로. 표는 scr 순(스크립트가 이미 정렬해서 낸다) 그대로 옮긴다.

   ## 종목 후보
   ([스크리닝] 상위/하위를 표로: | 티커 | scr(위험조정) | 1개월 | z | 베타 | 소속 |
    **하위 중 베타가 큰 것은 위험만 지고 지는 조합**이라 따로 짚는다.
    같은 섹터인데 상위·하위가 갈리면 그 사실이 제일 중요하다 —
    섹터 전체를 피할 게 아니라 그 안에서 갈라야 한다는 뜻이므로)

   ## 뉴스 연계 종목
   ([종목] 절이 있으면 같은 형식 표 + 왜 오늘 뉴스와 연결되는지 한 줄.
    없으면 '오늘 다이제스트에서 뽑을 상장 종목 없음')

   ## 모델 포트폴리오
   ([포지션 사이징] 절을 표로: | 티커 | 비중 | 소속 |. 비중은 flat 20%가 아니라
    역변동성 가중이라 종목마다 다르다 — 표에 그대로 옮기고 \"변동성 낮은 종목에 더
    담았다\"는 걸 한 줄 짚는다. 그 아래에 북 베타·추적오차·분산비율·
    연환산 초과수익(표본내)·정보비율(표본내)·최대낙폭(절대)을 한 줄로. **추적오차는 대회
    평가축(벤치 대비 상대수익) 그 자체가 얼마나 흔들릴 수 있는지다** 라고 짚는다.
    '표본내' 두 수치는 방금 그 종목을 고른 기준과 같은 구간에서 잰 값이라 부풀려져
    있다는 스크립트의 ※ 문장을 그대로 옮긴다. 제외된 종목이 있으면 어떤 종목과 상관이
    높아서 빠졌는지 적는다. '과거 관측치이지 예측이 아니다'를 반드시 남긴다.
    마지막 줄에 **항상** '백테스트: ' 로 시작하는 줄을 하나 쓴다 — [백테스트] 절의
    상태를 그대로 옮긴다: '아직 없음'이면 '백테스트: 아직 없음', 🔴 캐시 오래됨/깨짐
    경고면 그 경고 문장 그대로(숫자는 절대 지어내지 않는다), 신선한 숫자가 있으면
    \"백테스트: 같은 방법론(그룹 로테이션)이 최근 N회 중 M회 벤치를 이겼다(적중률%)\"
    처럼 인용한다 — 오늘 고른 종목이 아니라 **규칙 자체**의 과거 성적임을 분명히 한다.
    이 줄을 매번 쓰는 이유는 daily-conclusion.sh 가 이 '백테스트:' 줄이 있는지로
    텔레그램에 인용할지 말지를 판단하기 때문이다 — 줄 자체가 없으면 판단할 수가 없다)

   ## 전략모드
   ([전략모드] 절 한 줄 그대로 — 오늘은 로테이션/스크리닝/균형 중 뭘 위주로 볼지)

   ## 모멘텀·최근 흐름
   ([모멘텀] 절 그대로 (과열·과매도 없으면 '없음'). 이어서 [빌드업] 절 그대로 —
    레짐·1등 그룹이 며칠째 유지되는지, 브레드스가 넓어지는지 좁아지는지)

   ## 체결 추적
   ([체결추적] 절 그대로 — 티커별로 진입일·진입가·현재가·수익률·벤치 대비 초과수익·
    보유일수. '기록된 체결 없음'이면 그 문장 그대로 적는다. 이건 스크립트의 신호가
    아니라 **사람이 실제로 산 것**의 결과이므로 다른 절과 헷갈리지 않게 절 제목을
    분명히 구분한다. 초과수익이 마이너스로 돌아선 게 있으면 먼저 짚는다 —
    신호는 맞았는데 체결이 늦었는지, 신호 자체가 틀렸는지는 여기 적힌 진입일의
    [빌드업]/[백테스트] 상태를 나중에 대조해 볼 수 있게 숫자만 정확히 옮긴다.
    종목 아래 🔴/🟡 청산 후보 줄이 있으면 **그대로 옮기고 먼저 적는다** — 매도
    지시가 아니라 점검 필요 통지라는 걸 분명히 한다)

   ## 장의 성격
   ([브레드스] 그대로 + [실적발표 14일 내] 가 있으면 그 목록.
    발표가 임박한 종목은 추세추종이 아니라 이벤트 베팅이 된다고 적는다)

   ## 주의
   - [스트레치] 절: |z| 큰 것 = 벤치마크 대비 과열/과매도. 평균회귀 후보
   - [상관] 절에서 0.8 이상인 쌍: **둘 다 사면 분산이 아니라 같은 베팅**이다.
     대회에 포지션당 20% 상한이 있어도 상관이 높으면 실질 집중이 된다는 뜻이라 꼭 적는다
   - 베타가 큰데 초과수익이 마이너스인 항목: 위험만 지고 못 이기는 조합이라 짚는다
   - [모멘텀] 에 뜬 종목 중 [스크리닝] 상위와 겹치는 것: 방금 이겼는데 RSI 도 과열이면
     쫓아 사는 셈이라는 뜻이므로 따로 짚는다

