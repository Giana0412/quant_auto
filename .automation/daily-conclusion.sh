#!/bin/bash
# 분석봇: 오늘의 뉴스 다이제스트 + 시장 스냅샷을 종합해 "오늘의 결론"을 만들고
# 텔레그램으로 발송한다. 독립 launchd 잡이 아니라 evening-chain.sh 의 3단계로
# 순서대로 불린다 (뉴스레터 → 시장봇 → 이 스크립트 → 건강검진, §evening-chain.sh 참고).

set -euo pipefail

VAULT_DIR="/Users/gyuhyeongkim/orca/projects/quant_auto"
CLAUDE_BIN="/Users/gyuhyeongkim/.local/bin/claude"
LOG_DIR="$VAULT_DIR/.automation/logs"
LOG_FILE="$LOG_DIR/$(date +%Y%m%d).log"

mkdir -p "$LOG_DIR"
cd "$VAULT_DIR"

# 네트워크 대기·재시도 — 깨어난 직후 Wi-Fi 가 안 올라온 상태에서 죽는 것을 막는다.
# 대기 기록도 일별 로그에 남긴다 (건너뛴 이유가 어딘가엔 있어야 한다).
source "$VAULT_DIR/.automation/lib/net.sh"
if ! wait_for_network >> "$LOG_FILE" 2>&1; then
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') 네트워크 없음 — 이번 실행 건너뜀 ===" >> "$LOG_FILE"
  exit 0
fi


# 체인이 자정을 넘겨도 단계들이 같은 날짜를 쓰도록 CHAIN_DATE 를 우선한다
TODAY_KST="${CHAIN_DATE:-$(TZ=Asia/Seoul date +%y%m%d)}"
TODAY_ISO_KST=$(TZ=Asia/Seoul date -j -f %y%m%d "$TODAY_KST" +%Y-%m-%d)
CONCLUSION_PATH="personal/10-market/_conclusions/${TODAY_KST}-오늘의결론.md"
EASY_PATH="personal/10-market/_conclusions/${TODAY_KST}-오늘의결론-쉬운설명.md"

PROMPT="오늘 날짜(KST): ${TODAY_ISO_KST} (YYMMDD: ${TODAY_KST})

용도: **블룸버그 터미널 매매대회 전략 세팅용 아침 브리핑.** 한국장 개장(09:00) 전에
읽고 그날 포지션을 잡는 데 쓴다. 대회는 전 세계 주식을 사고 평가는 벤치마크 대비
상대수익률이므로, **벤치마크를 이기는 쪽이 어디인가**만 중요하다.

입력:
- personal/10-market/data/${TODAY_KST}-시장데이터.md (지표, 있을 수도 없을 수도)
- personal/09-newsletters/_digests/${TODAY_KST}-일일요약.md (뉴스, 있을 수도 없을 수도)

작업:
1. 둘 다 없으면 '오늘 종합할 자료 없음 — 결론 생략'만 출력하고 끝낸다.
2. 있는 것만 읽어 종합한다. **없는 숫자를 지어내지 않는다.**
3. ${CONCLUSION_PATH} 를 작성한다. **오늘 날짜로 이미 있어도 Edit 이 아니라 Write 로
   전체를 새로 써서 덮어쓴다** (allowedTools 에 Edit 이 없어 부분 수정은 헤드리스에서
   승인 없이 그대로 멈춘다 — market-snapshot.sh 와 같은 이유). 텔레그램 Markdown 만 쓴다 (*bold*, \`code\`).
   **중요**: _italic_ 문법은 쓰지 않는다 — 파일 경로의 언더스코어와 겹치면 짝이 안 맞아
   메시지 전체 발송이 실패한다. 강조는 *bold* 만, 경로는 \`백틱\` 으로 감싼다.
   형식 (없는 절은 통째로 생략, 전체 50줄 이내 — 절이 늘 때마다 올려 왔다:
   22 → 30(*빌드업*·*체결 대조*) → 32(*모델 북* 섹터 합계) → 36(*뉴스 대조*) →
   42 → 50(*워치리스트*·*일정*). 🔴 2026-09-13 실전 실행이 **정확히 36줄**로 상한에
   닿은 적이 있다 — LLM 이 상한을 지키려 압축한 결과이므로 여유를 두는 게 맞다.
   길이의 진짜 제약은 줄 수가 아니라 텔레그램 메시지 4096자인데 실측 3320바이트라
   아직 여유가 있다. *체결 대조*(기록 없으면)·*뉴스 대조*(어긋난 종목 없으면)·
   *워치리스트*(아무도 안 넣었으면)·*일정*(D-14 내 없으면)은 통째로 생략되므로
   보통은 30줄 안팎이다):

📈 *마켓 ${TODAY_ISO_KST}*

*레짐*
(벤치마크 50MA 위/아래 · VIX · 브레드스 %와 장의 성격. 한 줄로. 이어서 [전략모드]
 절 한 줄 그대로 붙인다 — 오늘은 로테이션 위주냐 스크리닝 위주냐)

*빌드업* (최근 흐름)
(시장데이터.md 의 '모멘텀·최근 흐름' 절 중 [빌드업] 부분: 레짐·1등 그룹이 몇 회째
 유지되는지, 브레드스가 넓어지는지 좁아지는지. 단위는 '일째'가 아니라 '회째'다(실행을
 건너뛴 날은 로그에 구멍이 나므로) — 그대로 옮긴다. '기록 1회째'면 '누적 시작' 정도로
 한 줄만 적고 넘어간다. 방금 뒤집힌 신호(1~2회째)는 아직 검증 안 됐다고 짚는다)

*이기는 쪽* (위험조정순 상위 — scr = 변동성 대비 초과수익)
(시장데이터.md의 ## 벤치마크 대비 초과수익(지역/섹터/스타일) 표에서 scr 상위 3개까지,
 초과수익과 함께. **RS 지속일을 같이 적는다** — 승10일과 승1일은 다르다. [모멘텀] 에
 RSI 과열로 뜬 것이 섞여 있으면 '단기 되돌림 위험'을 같이 적는다. scr 은 높은데 1개월
 초과수익이 작으면 '변동성 낮게 꾸준히 이기는 중'이라고 짚는다. 🔴 이 절은 ETF 로 계산한
 로테이션 신호다 — \"어느 지역/섹터/스타일이 이기는가\"라는 시황이지, 그 이름 자체가
 매수 대상이 아니다(대회는 ETF 매매 금지). 실제 살 수 있는 티커는 아래 *종목 후보* 절뿐
 이므로 헷갈리지 않게 이 절 끝에 그 사실을 한 줄로 짧게 남긴다)

*지는 쪽*
(마이너스 하위 2~3개. **베타가 큰데 마이너스면 위험만 지는 조합**이라 베타를 같이 적는다.
 3개월은 플러스인데 RS 가 패로 돌아선 것이 있으면 그게 제일 중요하니 먼저 적는다)

*종목 후보*
(스크리닝 상위(scr 순) 2~3개를 티커·초과수익·베타로. 그 다음 줄에 피할 것 —
 하위 중 베타 큰 것들을 묶어서. 같은 섹터인데 상위·하위가 갈리면 그 사실을 적는다.
 RSI 과열(⚡)이 붙은 후보는 '쫓아 사는 중'이라고 짧게 짚는다)

*워치리스트* (팀이 넣은 종목)
(시장데이터.md 의 '워치리스트' 절이 있으면: 티커·담당자·1개월 초과수익을 한 줄씩,
 지고 있는 것 먼저. '⏸안움직임' 표시가 있으면 그대로 붙인다. 마지막에 'N중 M개
 벤치 상회' 한 줄. 절이 없으면 이 절 통째로 생략한다 — 아직 아무도 안 넣었다는
 뜻이지 팀이 조사를 안 했다는 뜻이 아니므로 지어내지 않는다. 이건 스크립트 신호가
 아니라 **팀원이 근거를 갖고 넣은 것**이라 *종목 후보*와 구분해서 적는다)

*일정*
(시장데이터.md 의 '매크로 일정' 절에서 D-14 이내 항목만 한 줄로 묶는다.
 ⚠️미확인 표시가 붙은 건 그 표시를 빼지 않는다 — 확인 안 된 날짜다.
 D-14 안에 아무것도 없으면 이 절 생략)

*뉴스 대조* (센티멘트 vs 가격)
(시장데이터.md 의 '뉴스 대조' 절에서 🟢/🔴 로 어긋난 종목만 최대 3개. 형식은
 '티커 — 판정 · 근거 헤드라인 한 조각'. **근거 헤드라인을 반드시 붙인다** — 이 점수는
 헤드라인에서 기계적으로 센 것이라 오탐이 있고(제목에 티커는 있는데 본문 주인공이
 다른 회사인 경우), 읽는 사람이 그 한 줄로 기각할 수 있어야 한다.
 🟢 는 '호재인데 아직 안 올랐다', 🔴 는 '악재인데 안 빠졌다'로 짧게 푼다.
 ⚪ 반영됨은 그 종목이 *종목 후보*나 *모델 북*에 있을 때만 한 줄 — '이미 올라서
 쫓아 사는 것'이라고 짚는다. 절이 없거나 어긋난 종목이 없으면 이 절 통째로 생략)

*주의*
(상관 0.8 이상 쌍이 있으면: 둘 다 사면 분산이 아니라 같은 베팅.
 스트레치(|z|>=1.5) 있으면 평균회귀 후보로 적는다. 둘 다 없으면 이 절 생략)

*종목*
(뉴스 연계 종목이 있으면 벤치 대비 1개월 초과수익과 함께. 없으면 생략)

*이벤트*
(실적발표 14일 내 목록이 있으면 D-N 으로. 없으면 이 절 생략)

*모델 북* (목표 6종목 · 섹터 상한 · 20% 상한 · 역변동성 배분)
([포지션 사이징] 절 그대로: 티커·비중(더 이상 균등 20%가 아니다)·[섹터] 나열 + 북 베타 +
 추적오차 + 정보비율(표본내) + 최대낙폭(절대). '섹터 합계' 줄을 반드시 한 줄 옮긴다 —
 1차 미팅에서 정한 비중(테크 50 / 에너지 20 / 헬스케어 20 / 파이낸셜 10)대로 담겼는지가
 이 절의 핵심이다. 제외된 종목이 있으면 왜 빠졌는지 한 줄 — '상관 과다'와 '섹터 상한 소진'은
 뜻이 완전히 다르니 구분해서 적는다(전자는 분산이 안 돼서, 후자는 그 섹터를 이미 다 채워서다.
 후자는 '그 섹터가 좋은데 더 못 담았다'는 뜻이라 다음 순환 후보로 적어둔다). 추적오차가 크면
 '변동성 큰 상대수익'이라고 짚는다. 정보비율(표본내)은 방금 그 종목을 고른 기준과
 같은 구간에서 잰 값이라 원래 높게 나온다 — 낮게 나왔을 때만 '위험 대비 효율이
 낮다'고 짚고, 높다고 '검증됐다'는 식으로 쓰지 않는다.
 시장데이터.md 의 '백테스트: ' 줄을 마지막에 한 줄 그대로 옮긴다 — '아직 없음'이면
 이 문장 생략, 🔴 경고문이면 경고문 그대로(숫자를 지어내지 않는다), 숫자가 있으면
 \"같은 로테이션 방법론이 최근 N회 중 M회 벤치를 이겼다(적중률%) — 오늘 종목이 아니라
 규칙 자체의 과거 성적, 다음 구간 실현수익 기준이라 편향 없음\".
 🔴 여기에 \"표본 12회라 창이 며칠만 밀려도 33~67% 를 오간다 — 지난주와 비교하지 말 것\"
 을 반드시 덧붙인다. 이 숫자는 주 단위로 크게 흔들려서(9/11 42% → 9/13 17%, 시장이
 아니라 데이터 창이 밀린 것) 경고 없이 내보내면 팀이 전략이 나빠졌다고 읽는다)

*체결 대조* (실제 진입 vs 신호)
(시장데이터.md 의 '체결 추적' 절 그대로: 티커·진입일·수익률·벤치 대비 초과수익.
 '기록된 체결 없음'이면 **이 절 자체를 통째로 생략한다** — 로그에 아직 없다는
 뜻이지 오늘 매매를 안 했다는 뜻이 아니므로 '매매 없음'이라고 지어내지 않는다.
 종목 아래 🔴/🟡/🟢 로 시작하는 청산 후보 줄이 있으면 **그 종목을 맨 위에, 경고
 문구 그대로** 적는다 — 스크립트가 계산한 손절/익절 후보 통지이지 매도 지시가
 아니므로 '점검 필요'라고 짚되 '팔아라'라고 단정하지 않는다.
 🟢 목표도달은 다른 셋과 성격이 다르다 — 1차 미팅에서 '섹터별 목표 수익률에
 도달하면 즉시 매도하고 다음 섹터로 순환'을 룰로 정했으므로, 이건 나쁜 소식이
 아니라 **예정된 순환 시점**이다. 맨 위에 적고 '팀 룰상 정리 후 다음 섹터'라고
 짚되, 역시 매도 지시로 단정하지는 않는다. 청산 후보가 없는
 종목 중에선 초과수익이 마이너스로 돌아선 것을 먼저 적는다. 이건 스크립트 신호가
 아니라 **사람이 실제로 산 결과**이니 *모델 북*·*이기는 쪽*과 헷갈리지 않게
 구분한다. 신호가 틀렸는지 체결 타이밍이 늦었는지는 판단하지 말고 숫자만 옮긴다)

*뉴스*
- (매매 판단에 영향 있는 것만 1줄씩, 최대 3개)

원문: \`personal/10-market/data/...\`

4. 파일을 쓴 뒤 텔레그램 **팀 그룹**에 발송한다:
   .automation/send_telegram.sh ${CONCLUSION_PATH} --to group
   (--to group 을 빼먹으면 팀이 아니라 개인방으로 간다. 스크립트가 미설정이면 조용히
    건너뛰므로 실패로 취급하지 않는다. 출력을 그대로 보고한다.)

5. ${EASY_PATH} 를 작성한다 — 같은 내용을 **왜 그런지까지 풀어쓴** 버전.
   숫자만 나열하지 말고 '이게 무슨 뜻이냐'를 설명한다. 예를 들어 베타가 4인 자산은
   벤치마크가 1% 움직일 때 4% 움직인다는 뜻이고, 상관이 0.95면 두 개를 나눠 사도
   한 곳에 몰아넣은 것과 같다는 식으로. 20줄 정도까지.
   여기서도 _italic_ 은 쓰지 않는다. **원본에 없는 숫자·사건을 만들지 않는다.**
6. ${EASY_PATH} 도 같은 그룹에 발송한다:
   .automation/send_telegram.sh ${EASY_PATH} --to group

personal/10-market/_conclusions/ 외의 다른 파일은 건드리지 않는다. git commit/push는 하지 않는다."

{
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') [분석봇] 실행 시작 ==="
  retry 3 60 "$CLAUDE_BIN" -p "$PROMPT" --allowedTools "Read Write Glob Grep Bash(.automation/send_telegram.sh:*)" 2>&1
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') [분석봇] 실행 종료 ==="
  echo
} >> "$LOG_FILE"
